TrackLanes.StartPosition = Vector3.new(-24.68, 7.27, 24.16)
TrackLanes.StartDirection = Vector3.new(0.9992, 0.0000, 0.0409)

function TrackLanes.ToWorld(trackModel: Model, localPos: Vector3): Vector3
	local origin = trackModel:FindFirstChild("TrackOrigin", true) :: BasePart
	return origin.CFrame:PointToWorldSpace(localPos)
end

function TrackLanes.StartCFrame(trackModel: Model): CFrame
	local pos = TrackLanes.ToWorld(trackModel, TrackLanes.StartPosition)
	local origin = trackModel:FindFirstChild("TrackOrigin", true) :: BasePart
	local dir = origin.CFrame:VectorToWorldSpace(TrackLanes.StartDirection)
	return CFrame.lookAt(pos, pos + dir)
end

return TrackLanes
